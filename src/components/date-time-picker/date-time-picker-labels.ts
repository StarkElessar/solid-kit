export interface DateTimePickerLabels {
	/** Имя кнопки-значка в поле. */
	openPicker: string;
	clear: string;
	/** Имя диалога с календарём и колонками времени. */
	panel: string;
	now: string;
	/** Названия частей даты для подсказки в поле: «дд.мм.гггг». */
	day: string;
	month: string;
	year: string;
	/** Названия частей времени для подсказки в поле: «чч:мм». */
	hourPart: string;
	minutePart: string;
	/** Имена колонок времени. */
	hours: string;
	minutes: string;
	/** Имя колонки AM и PM, а также часть подсказки 12-часового вида. */
	period: string;
}
