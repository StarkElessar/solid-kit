import { describe, expect, it } from 'vitest';

import { foundText } from './found-text';

describe('foundText', () => {
	it.each([
		[0, 'Найдено 0 записей'],
		[1, 'Найдена 1 запись'],
		[2, 'Найдено 2 записи'],
		[4, 'Найдено 4 записи'],
		[5, 'Найдено 5 записей'],
		[11, 'Найдено 11 записей'],
		[12, 'Найдено 12 записей'],
		[21, 'Найдена 21 запись'],
		[22, 'Найдено 22 записи'],
		[25, 'Найдено 25 записей'],
		[100, 'Найдено 100 записей'],
		[101, 'Найдена 101 запись']
	])('%i → «%s»', (count, expected) => {
		expect(foundText(count)).toBe(expected);
	});
});
