/** Одна часть маскируемого текста (день, месяц, год, часы, минуты). */
export interface MaskField {
	/** Сколько цифр занимает заполненная часть. */
	readonly width: number;
	/** Дополнять часть нулями слева, когда она закрыта разделителем или невозможностью второй цифры. */
	readonly pad: boolean;
	/** Если первая цифра больше этого числа, вторая невозможна и часть закрывается сразу. */
	readonly maxFirstDigit?: number | undefined;
}
